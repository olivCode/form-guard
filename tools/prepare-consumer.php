<?php

declare(strict_types=1);
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}
$root = dirname(__DIR__);
$build = $root . '/build';
foreach ([$build, $build . '/distribution'] as $dir) {
    if (!is_dir($dir) && !mkdir($dir, 0700, true) && !is_dir($dir)) {
        throw new RuntimeException('Cannot create distribution directory.');
    }
}
$consumer = $build . '/consumer';

// Only reset our own generated fixture, inside this checkout's build directory.
if (is_dir($consumer)) {
    $resolvedBuild = realpath($build);
    $resolvedConsumer = realpath($consumer);
    $marker = $consumer . '/.form-guard-fixture';
    if (is_link($consumer) || $resolvedConsumer !== $resolvedBuild . DIRECTORY_SEPARATOR . 'consumer'
        || !is_file($marker) || file_get_contents($marker) !== 'generated by Form Guard distribution tests') {
        throw new RuntimeException('Refusing to reset an unknown consumer directory.');
    }
    $remove = static function (string $directory) use (&$remove, $resolvedConsumer): void {
        $real = realpath($directory);
        if ($real === false || ($real !== $resolvedConsumer && !str_starts_with($real, $resolvedConsumer . DIRECTORY_SEPARATOR)) || is_link($directory)) {
            throw new RuntimeException('Fixture cleanup escaped its root.');
        }
        foreach (new DirectoryIterator($directory) as $entry) {
            if ($entry->isDot()) {
                continue;
            }
            $path = $entry->getPathname();
            if ($entry->isLink()) {
                throw new RuntimeException('Unexpected link in consumer fixture.');
            }
            if ($entry->isDir()) {
                $remove($path);
                if (!rmdir($path)) {
                    throw new RuntimeException('Cannot remove fixture directory.');
                }
            } elseif (!unlink($path)) {
                throw new RuntimeException('Cannot remove fixture file.');
            }
        }
    };
    $remove($consumer);
} elseif (!mkdir($consumer, 0700)) {
    throw new RuntimeException('Cannot create consumer fixture.');
}
file_put_contents($consumer . '/.form-guard-fixture', 'generated by Form Guard distribution tests');

$metadata = json_decode(file_get_contents($root . '/composer.json'), true, 512, JSON_THROW_ON_ERROR);
$archive = str_replace('\\', '/', realpath($build . '/distribution')) . '/form-guard.zip';
// PHP's local file wrapper expects a filesystem path, including literal spaces.
$fileUrl = 'file://' . (str_starts_with($archive, '/') ? '' : '/') . $archive;
$package = array_intersect_key($metadata, array_flip(['name', 'description', 'type', 'license', 'require', 'autoload', 'bin']));
$package['version'] = '1.0.0';
$package['dist'] = ['type' => 'zip', 'url' => $fileUrl];
$fixture = [
    'name' => 'form-guard-tests/consumer',
    'type' => 'project',
    'license' => 'proprietary',
    'repositories' => [['type' => 'package', 'package' => $package], ['packagist.org' => false]],
    'require' => [$metadata['name'] => '1.0.0'],
    'minimum-stability' => 'dev',
    'config' => ['allow-plugins' => false],
];
file_put_contents($consumer . '/composer.json', json_encode($fixture, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo "Fresh consumer fixture prepared; all packages resolve locally.\n";
